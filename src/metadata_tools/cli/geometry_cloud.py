"""GCP dispatch entry point for geometry table generation across all hosts.

Dispatches geometry generation to GCP via rms-cloud-tasks; use
``metadata-geometry-worker`` for local parallel runs.

Argument defaults (the run-directory workflow):

  --config     Defaults to ``cloud/<HOST>/gcp_geometry_config.yml`` when that file exists.
               Bare filenames resolve against ``cloud/<HOST>/``.
  --task-file  Defaults to ``./tasks.json`` when that exists in the current directory
               and no ``--task-file``, ``--volumes``, or ``--continue`` is given.
               Bare filenames resolve against ``cloud/<HOST>/``; use a ``./`` prefix
               (or an absolute path) for a file relative to the current directory.

So the typical dispatch, from a run directory holding a ``tasks.json`` generated by
``metadata-task-list GO_0xxx $RMS_METADATA/GO_0xxx/ --output tasks.json``:

  metadata-geometry-cloud GO_0xxx $RMS_METADATA_GCP/GO_0xxx/ \\
      $RMS_METADATA_TEST_GCP/GO_0xxx/ --use-spot

Or dispatch directly from a volume list (a temp task file is generated automatically):

  metadata-geometry-cloud GO_0xxx $RMS_METADATA_GCP/GO_0xxx/ \\
      $RMS_METADATA_TEST_GCP/GO_0xxx/ --use-spot --volumes GO_0022 GO_0016

Both flags can always be given explicitly and take precedence over the defaults:

  metadata-geometry-cloud GO_0xxx $RMS_METADATA_GCP/GO_0xxx/ \\
      $RMS_METADATA_TEST_GCP/GO_0xxx/ --use-spot \\
      --config my_gcp_config.yml --task-file ./retry_tasks.json

Instance software -- scratch install vs. a stored image:

  By default each instance boots a stock OS image and the startup script installs
  everything from scratch: apt python/git, then a fresh venv with
  ``pip install rms-metadata-tools[cloud]`` (or a git clone under --debug-branch).
  No extra flags are needed.

  To boot instances from a stored GCP image instead -- one baked with the OS
  packages and venv preinstalled -- pass cloud_tasks' ``--image`` with an image
  family name (the family's latest image is used, so a rebaked image is picked up
  without touching any config) or a full image URI:

    metadata-geometry-cloud GO_0xxx $RMS_METADATA_GCP/GO_0xxx/ \\
        $RMS_METADATA_TEST_GCP/GO_0xxx/ --use-spot --image metadata-tools-worker

  The same choice can be stored per stage in the config YAML's provider section:

    gcp:
      image: metadata-tools-worker

  The startup script still runs on a stored image; its install steps largely
  reduce to no-ops against the preinstalled software. Pair with
  --startup-template to skip installation altogether.

To preview the startup script that would be sent to GCP instances:

  metadata-geometry-cloud GO_0xxx $RMS_METADATA_GCP/GO_0xxx/ \\
      $RMS_METADATA_TEST_GCP/GO_0xxx/ --create-startup-file startup.sh

Command-line arguments:

  HOST_ID                     Host directory, e.g. GO_0xxx or COISS_xxxx. It must
                              come first.
  metadata_tree               Top of the tree holding the volumes' index files.
  output_tree                 Top of the tree in which the geometry tables are
                              written. For hosts with an index stage, it holds the
                              supplemental index files.
  --volumes [VOLUME ...]      Process only these volumes. This disables --new_only.
  --exclude, -e [VOLUME ...]  Skip these volumes. The default is the host's
                              configured list or, failing that, the collection's
                              cumulative volume.
  --new_only, -n              Skip volumes that already contain an *_inventory.csv.
  --first, -f N               Process at most N files in each volume.
  --pattern, -p PATTERN       Process only the files whose path matches this glob
                              pattern.
  --labels, -l                Write labels for existing tables; compute no geometry.
  --sampling, -s N            Pixel sampling density of the field-of-view meshgrid
                              (default 8).
  --body-samples, -b N        Minimum number of samples across the bounding box of
                              each body (default 16).
  --no-body-meshgrids         Sample every body on the field-of-view meshgrid rather
                              than on a meshgrid of its own.
  --help, -h                  Print a summary of the arguments and exit.

Dispatch arguments, which are not passed to the workers:

  --config FILE               cloud_tasks configuration. The default is
                              cloud/<HOST>/gcp_geometry_config.yml, if it exists.
  --task-file FILE            Task list. The default is ./tasks.json, if it
                              exists and neither --volumes nor --continue is
                              given. --volumes is turned into a temporary task
                              file.
  --create-startup-file FILE  Write the instances' startup script to FILE and exit
                              without dispatching.
  --startup-template FILE     Build the startup script from FILE instead of the
                              packaged template.
  --oops-resources NAME       Persistent disk holding the OOPS resources.
  --service-account ACCOUNT   GCP service account (overrides $GCP_SERVICE_ACCOUNT).
  --debug-branch BRANCH       Git branch to clone on the instances (overrides
                              $GCP_DEBUG_BRANCH).
  --ssh-paste                 With --create-startup-file, replace ``cd /root`` with
                              ``cd ~`` so the script can be pasted into an SSH
                              terminal as a non-root user.

All other ``cloud_tasks run`` arguments are also accepted and passed to it, for
example --use-spot, --image, --max-instances and --continue; ``cloud_tasks run
--help`` lists them all.

The user guide describes the options in more detail.
"""
import sys
from pathlib import Path

from metadata_tools.cli._host import (
    build_startup_script,
    cloud_dir_for,
    default_config_arg,
    default_task_file_arg,
    dispatch_cloud_run_if_config,
    load_host,
    pop_argv_bool_flag,
    pop_argv_flag,
    resolve_host_paths,
    volumes_as_task_file,
)
from metadata_tools.config import get_exclude, get_host_config, set_host

_WORKER = 'metadata-geometry-worker'


def main() -> None:
    """Entry point for the ``metadata-geometry-cloud`` console script."""
    if len(sys.argv) < 2 or sys.argv[1].startswith('-'):
        sys.exit('Usage: metadata-geometry-cloud HOST_ID [args...]')
    host_id = sys.argv[1]
    host_dir = load_host(host_id)
    resolve_host_paths(host_dir, cloud_dir_for(host_id))
    default_config = default_config_arg(host_id, 'geometry')
    default_task_file_arg()

    create_startup_file = pop_argv_flag('--create-startup-file')
    startup_template = pop_argv_flag('--startup-template')
    oops_resources = pop_argv_flag('--oops-resources')
    service_account = pop_argv_flag('--service-account')
    debug_branch = pop_argv_flag('--debug-branch')
    ssh_paste = pop_argv_bool_flag('--ssh-paste')

    if '--config' not in sys.argv and create_startup_file is None:
        sys.exit(f'metadata-geometry-cloud requires --config (no default config at '
                 f'{default_config}; defaults exist only in a source checkout); '
                 'use metadata-geometry-worker for local runs')

    set_host(host_id)
    hconf = get_host_config()

    import metadata_tools.util as util
    from metadata_tools.geometry_support import get_args

    host, _, _ = util.parse_template_name(hconf.template_name)
    parser = get_args(host=host, exclude=get_exclude())

    if create_startup_file is not None:
        Path(create_startup_file).write_text(
            build_startup_script(host_id, parser, _WORKER, startup_template, oops_resources,
                                 debug_branch, for_ssh=ssh_paste),
            encoding='utf-8',
        )
        sys.exit(0)

    with volumes_as_task_file():
        rc = dispatch_cloud_run_if_config(host_id, parser, worker_cmd_name=_WORKER,
                                          startup_template=startup_template,
                                          oops_resources=oops_resources,
                                          service_account=service_account,
                                          debug_branch=debug_branch)
    sys.exit(rc)
